## 1.1 Formål

Disse Provider Terms & Conditions ("Betingelserne") regulerer forholdet mellem MyCleaner International Ltd ("MyCleaner") og enhver person eller virksomhed ("Provideren"), der opretter en Provider-konto eller tilbyder ydelser gennem MyCleaner-platformen.

Formålet med disse Betingelser er at skabe en sikker, gennemsigtig og professionel markedsplads, hvor både kunder og Providere kan samarbejde under klare og fair regler.

## 1.2 Platformens rolle

MyCleaner driver en digital markedsplads, der forbinder kunder med selvstændige Providere.

MyCleaner leverer blandt andet:

- bookingplatform
- betalingsinfrastruktur
- kommunikationsværktøjer
- identitetsverifikation
- supportfunktioner
- sikkerhedssystemer
- AI-baserede hjælpefunktioner
- kvalitetskontrol

Medmindre ufravigelig lovgivning bestemmer andet, udfører MyCleaner ikke selv de ydelser, der bestilles gennem platformen, og er ikke arbejdsgiver for Provideren.

## 1.3 Providerens status

Provideren er en selvstændig erhvervsdrivende eller handler i eget navn og for egen regning.

Provideren er selv ansvarlig for:

- overholdelse af gældende lovgivning
- skat
- moms
- forsikringer
- tilladelser
- nødvendige registreringer
- udførelse af de aftalte ydelser

Intet i disse Betingelser etablerer et ansættelsesforhold, partnerskab, agentur eller joint venture mellem MyCleaner og Provideren.

## 1.4 Accept

Ved oprettelse af en Provider-konto, gennemførelse af identitetsverifikation, accept af en booking eller fortsat brug af platformen accepterer Provideren disse Betingelser.

Provideren erklærer samtidig, at alle afgivne oplysninger er korrekte, fuldstændige og ajourførte.

## 1.5 Ændringer

MyCleaner kan opdatere disse Betingelser for blandt andet at:

- overholde gældende lovgivning
- forbedre platformens sikkerhed
- introducere nye funktioner
- beskytte platformens integritet
- forbedre brugeroplevelsen

Ved væsentlige ændringer kan Provideren blive bedt om at acceptere den nye version, før platformen kan anvendes videre.

## 1.6 Prioritet

Ved konflikt mellem dokumenter gælder følgende rækkefølge:

1. Gældende lovgivning
